-- Текстовое поле с ролью аналитики «измерение» (1.8.0, решение владельца 9; docs/specs/awareness.md, раздел 7.1):
-- «Подразделение» в реестрах «Сотрудники» и «Результаты INDIGO» — текст, по нему строятся виджет распределения и фильтр.
-- Ограничение register_fields_analytics_check пересоздаётся с более широким условием: к типам с ролью 'dimension'
-- добавлен 'text'. Остальные пары тип — роль не меняются.
--
-- Влияние на данные: строки не меняются (0 строк). Все существующие строки register_fields новому условию
-- соответствуют: оно только шире прежнего. ADD CONSTRAINT проверяет таблицу полей реестров — она маленькая.
-- Откат на 1.7.0 без отката базы совместим: 1.7.0 текстовым полям роль не ставит (проверка в приложении при смене
-- роли), а поле с ролью, поставленной в 1.8.0, показывает пустым распределением; переименование такого поля и снятие
-- роли в 1.7.0 работают (проверено по коду v1.7.0: роль проверяется только при её смене).
-- Откатывать саму миграцию не нужно; если понадобится — прежнее условие, после снятия роли у текстовых полей.

ALTER TABLE "register_fields"
  DROP CONSTRAINT "register_fields_analytics_check",
  ADD CONSTRAINT "register_fields_analytics_check" CHECK (
    "analytics_role" IS NULL
    OR ("type" IN ('select', 'decision', 'user', 'catalog', 'text') AND "analytics_role" = 'dimension')
    OR ("type" = 'number' AND "analytics_role" = 'metric')
    OR ("type" IN ('date', 'calc') AND "analytics_role" IN ('date', 'deadline'))
  );
